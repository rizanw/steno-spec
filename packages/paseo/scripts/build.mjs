// Generates server/vendor/: the language server, the CLI and the skills that `steno init` installs, embedded as
// text, and core's host rules bundled with their JSON-RPC library. Paseo evaluates the compiled server entry with no
// file path and installs no npm dependencies, so nothing can be read from the plugin's folder at run time: its
// compiler inlines both modules, and server/programs.ts writes the programs back to disk before running them.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const here = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(here, '..', '..');
const vendor = join(here, 'server', 'vendor');

rmSync(vendor, { recursive: true, force: true });
mkdirSync(vendor, { recursive: true });

// The programs are built by packages/cli, which runs first because it is a devDependency of this package.
const programs = Object.fromEntries(['steno-lsp.mjs', 'steno-cli.mjs'].map(f => [f, readFileSync(join(root, 'packages', 'cli', 'bin', f), 'utf8')]));
const skillsDir = join(root, 'packages', 'skills', 'skills');
const skills = Object.fromEntries(readdirSync(skillsDir, { recursive: true, withFileTypes: true }).filter(e => e.isFile())
  .map(e => join(e.parentPath, e.name)).sort().map(f => [relative(skillsDir, f).split(sep).join('/'), readFileSync(f, 'utf8')]));
// The unpacked folder is named by this hash, so a plugin update never runs programs left by an older one.
const hash = createHash('sha256').update(JSON.stringify([programs, skills])).digest('hex').slice(0, 16);
writeFileSync(join(vendor, 'programs.ts'), [
  '// Generated by scripts/build.mjs from packages/cli/bin and packages/skills/skills. Do not edit.',
  `export const HASH = ${JSON.stringify(hash)};`,
  `export const PROGRAMS: Record<'steno-lsp.mjs' | 'steno-cli.mjs', string> = ${JSON.stringify(programs)};`,
  `export const SKILLS: Record<string, string> = ${JSON.stringify(skills)};`,
  '',
].join('\n'));

// vscode-jsonrpc is CommonJS and requires Node built-ins, so the banner gives the module a `require`. Inside Paseo
// `import.meta.url` is undefined; only built-ins are required, so any file URL serves.
const entry = join(here, 'vendor-src', 'host.ts');
await build({
  entryPoints: [entry],
  outfile: join(vendor, 'host.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  banner: { js: "import { createRequire as __stenoCreateRequire } from 'node:module'; const require = __stenoCreateRequire(import.meta.url ?? 'file:///');" },
});

// The declarations, as `.d.mts` because TypeScript looks for that name beside an imported `.mjs`. They re-export
// from @steno/core and vscode-jsonrpc, which resolve here as devDependencies; Paseo only strips types.
const program = ts.createProgram([entry], {
  declaration: true, emitDeclarationOnly: true, module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler, target: ts.ScriptTarget.ES2022, strict: true, skipLibCheck: true,
});
let declarations;
const emitted = program.emit(program.getSourceFile(entry), (name, text) => { if (name.endsWith('.d.ts')) declarations = text; });
const errors = [...ts.getPreEmitDiagnostics(program), ...emitted.diagnostics];
if (errors.length || !declarations) {
  throw new Error(ts.formatDiagnostics(errors, { getCanonicalFileName: f => f, getCurrentDirectory: () => here, getNewLine: () => '\n' }) || 'no declarations emitted');
}
writeFileSync(join(vendor, 'host.d.mts'), declarations);

// The manifest's icon: brand art lives in assets/, so it is copied in rather than kept twice.
mkdirSync(join(here, 'media'), { recursive: true });
copyFileSync(join(root, 'assets', 'steno.png'), join(here, 'media', 'icon.png'));
